// Bundles the viewer's value formatters (RISC-V disassembler, alias tables, hex/oct/bin/dec/
// signed/ASCII) from the cmux VaporView fork's webview sources into
// Resources/vaporview/cmux-formats.js (window.cmuxFormats), for text breakpoints.
// Source: VaporView (GPL-3.0, https://github.com/Lramseyer/vaporview) with the cmux fork's
// additions (riscv_disasm.ts, value_alias.ts). The same approach as helper-v2's formats.js.
//   node build-formats.mjs <vaporview-cmux dir> <dir holding node_modules/esbuild>
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const here = path.dirname(new URL(import.meta.url).pathname);
const vv = path.resolve(process.argv[2]);
const esbuild = createRequire(path.join(path.resolve(process.argv[3]), 'package.json'))('esbuild');
const web = path.join(vv, 'src/webview');
// value_format.ts imports the page (vaporview.ts, signal_item.ts) for its enum and warning paths;
// the formatters used here never reach them, so those imports are stubbed.
const STUBS = {
  './vaporview': 'export const dataManager = {enumTable: {}}; export const vscodeWrapper = {showMessage() {}, outputLog() {}};',
  './signal_item': 'export {};',
  './extra_formats': 'export function getExtraValueFormat() { return undefined; }',
  '@js-temporal/polyfill': 'export const Temporal = undefined;',
};
const stub = { name: 'stub', setup(b) {
  b.onResolve({ filter: /.*/ }, (a) => (STUBS[a.path] !== undefined && a.importer.endsWith('value_format.ts') ? { path: a.path, namespace: 'stub' } : undefined));
  b.onLoad({ filter: /.*/, namespace: 'stub' }, (a) => ({ contents: STUBS[a.path], loader: 'ts' }));
} };
const SOURCES = ['riscv_disasm.ts', 'value_alias.ts', 'value_format.ts', 'value_search.ts'].map((f) => 'src/webview/' + f);
const rev = execFileSync('git', ['-C', vv, 'log', '-1', '--format=%h', '--', ...SOURCES]).toString().trim();
const out = path.resolve(here, '../../../Resources/vaporview/cmux-formats.js');
await esbuild.build({
  stdin: { contents: fs.readFileSync(path.join(here, 'formats-entry.ts'), 'utf8'), resolveDir: web, loader: 'ts', sourcefile: 'formats-entry.ts' },
  absWorkingDir: here, bundle: true, format: 'iife', globalName: 'cmuxFormats', platform: 'browser', target: ['es2020'],
  plugins: [stub], logLevel: 'warning', legalComments: 'none',
  banner: { js: `// GENERATED by scripts/waveform-viewer-checks/text/build-formats.mjs from vaporview-cmux ${rev}\n// (src/webview: riscv_disasm.ts, value_alias.ts, value_format.ts, value_search.ts). VaporView is\n// GPL-3.0 (https://github.com/Lramseyer/vaporview); the RISC-V disassembler and alias tables are the\n// cmux fork's own additions to it. Do not edit; rebuild.` },
  footer: { js: 'if (typeof self !== "undefined") { self.cmuxFormats = cmuxFormats; }' },
  outfile: out,
});
console.log(`built ${out} from ${vv} ${rev}`);
