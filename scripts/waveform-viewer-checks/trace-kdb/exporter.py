#!/usr/bin/env python3
# trace-kdb-exporter: npi-model.py's own reading of a KDB folder, without Verdi (no NPI is
# imported): the compile's parameter overrides from the daidir's vcs_rebuild (VCS's record of the
# compile command, with the -f files it names), and the compile time. Prints `ok`/`FAIL` lines
# and a verdict. Usage: python3 exporter.py <npi-model.py>
import importlib.util
import os
import sys
import tempfile

spec = importlib.util.spec_from_file_location("npi_model", sys.argv[1])
npi = importlib.util.module_from_spec(spec)
spec.loader.exec_module(npi)
failures = 0


def check(what, got, want):
    global failures
    if got == want:
        print("ok   " + what)
    else:
        failures += 1
        print("FAIL %s: %r, expected %r" % (what, got, want))


HERE = os.path.dirname(os.path.abspath(__file__))


def real(name):
    """A real vcs_rebuild from fixture/vcs_rebuild (see its README), as the file's text."""
    with open(os.path.join(HERE, "fixture", "vcs_rebuild", name)) as f:
        return f.read()


def daidir(root, rebuild=None, files=None, elab=None, raw=None):
    sim = os.path.join(root, "sim")
    d = os.path.join(sim, "simv.daidir")
    os.makedirs(os.path.join(d, "kdb.elab++"))
    if rebuild is not None or raw is not None:
        with open(os.path.join(d, "vcs_rebuild"), "w") as f:
            f.write(raw if raw is not None else "#!/bin/sh -e\n# This file is automatically generated by VCS.\n" + rebuild + "\n")
    for name, text in (files or {}).items():
        with open(os.path.join(sim, name), "w") as f:
            f.write(text)
    for name, mtime in (elab or {}).items():
        path = os.path.join(d, "kdb.elab++", name)
        open(path, "w").close()
        os.utime(path, (mtime, mtime))
    return d


with tempfile.TemporaryDirectory() as tmp:
    def case(name, **kw):
        root = os.path.join(tmp, name)
        os.makedirs(root)
        return daidir(root, **kw)

    check("no override: an empty list",
          npi.overrides(case("none", rebuild="vcs '-full64' '-sverilog' '+define+ALT' '-top' 'tb' 'fifo.sv'")), [])
    check("-pvalue: listed",
          npi.overrides(case("pvalue", rebuild="vcs '-sverilog' '-pvalue+tb.u_fifo.DEPTH=32' 'fifo.sv'")), ["-pvalue+tb.u_fifo.DEPTH=32"])
    check("-parameters <file>: listed with its file",
          npi.overrides(case("params", rebuild="vcs '-sverilog' '-parameters' 'p.txt' 'fifo.sv'")), ["-parameters p.txt"])
    check("an override in a -f file (next to the daidir): listed",
          npi.overrides(case("ffile", rebuild="vcs '-sverilog' '-f' 'files.f'",
                             files={"files.f": "fifo.sv\n// a comment\n-pvalue+tb.W=4\n"})), ["-pvalue+tb.W=4"])
    check("a -f file that can't be read: unknown (None)",
          npi.overrides(case("lost", rebuild="vcs '-sverilog' '-f' 'gone.f'")), None)
    check("no vcs_rebuild: unknown (None)", npi.overrides(case("norebuild")), None)
    # Real vcs_rebuild files (fixture/vcs_rebuild). The -f file is ../opts.f from where VCS ran.
    check("real, no override: an empty list", npi.overrides(case("real-none", raw=real("none"))), [])
    check("real, -pvalue in a -f file: listed",
          npi.overrides(case("real-ffile", raw=real("ffile"), files={"../opts.f": "-pvalue+tb.u_fifo.DEPTH=32\n"})),
          ["-pvalue+tb.u_fifo.DEPTH=32"])
    check("real, -pvalue from a shell variable (recorded expanded): listed",
          npi.overrides(case("real-cmdline", raw=real("cmdline"))), ["-pvalue+tb.u_fifo.DEPTH=8"])
    check("real, +pvalue+ (VCS takes it): listed", npi.overrides(case("real-plus", raw=real("plus"))), ["+pvalue+tb.u_fifo.DEPTH=4"])
    # Fail closed: anything the scan can't be sure it read in full is unknown (None), never [].
    check("an unexpanded variable on the command line: unknown",
          npi.overrides(case("var", rebuild="vcs '-sverilog' $VCS_OPTS 'fifo.sv'")), None)
    check("a variable in a -f file: unknown",
          npi.overrides(case("fvar", rebuild="vcs '-sverilog' '-f' 'files.f'", files={"files.f": "fifo.sv\n${PROJ}/opts\n"})), None)
    check("a command substitution: unknown",
          npi.overrides(case("subst", rebuild="vcs '-sverilog' `cat opts` 'fifo.sv'")), None)
    check("no vcs command (a wrapper that runs make): unknown",
          npi.overrides(case("make", rebuild="exec make -C .. sim")), None)
    check("an override spelling the scan doesn't list (any token naming pvalue or parameters): listed",
          npi.overrides(case("spell", rebuild="vcs '-sverilog' '-pvalues=tb.W=4' 'fifo.sv'")), ["-pvalues=tb.W=4"])
    check("the vcs command after cd and env lines: its arguments",
          npi.overrides(case("cdenv", rebuild="cd /work/sim\nexport LM_LICENSE_FILE=1\nvcs '-sverilog' '-pvalue+tb.W=2' 'fifo.sv'")), ["-pvalue+tb.W=2"])
    check("a KDB with no files: no compile time (None, not 0)", npi.compiled_at(case("empty")), None)
    check("the newest file's time, in ms", npi.compiled_at(case("dated", elab={"a.db": 1000, "b.db": 2000})), 2000000)

print("TRACE KDB EXPORTER CHECKS PASSED" if failures == 0 else "TRACE KDB EXPORTER CHECKS FAILED: %d" % failures)
sys.exit(1 if failures else 0)
