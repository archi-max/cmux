#!/usr/bin/env python3
# trace-kdb-exporter: npi-model.py's own reading of a KDB folder, without Verdi (no NPI is
# imported): the compile's parameter overrides from the daidir's vcs_rebuild (VCS's record of the
# compile command, with the -f files it names), and the compile time. Prints `ok`/`FAIL` lines
# and a verdict. Usage: python3 exporter.py <npi-model.py>
import importlib.util
import os
import sys
import tempfile

spec = importlib.util.spec_from_file_location("npi_model", sys.argv[1])
npi = importlib.util.module_from_spec(spec)
spec.loader.exec_module(npi)
failures = 0


def check(what, got, want):
    global failures
    if got == want:
        print("ok   " + what)
    else:
        failures += 1
        print("FAIL %s: %r, expected %r" % (what, got, want))


HERE = os.path.dirname(os.path.abspath(__file__))


def real(name):
    """A real vcs_rebuild from fixture/vcs_rebuild (see its README), as the file's text."""
    with open(os.path.join(HERE, "fixture", "vcs_rebuild", name)) as f:
        return f.read()


def daidir(root, rebuild=None, files=None, elab=None, raw=None, sub=""):
    sim = os.path.join(root, "sim")
    d = os.path.join(sim, sub, "simv.daidir")
    os.makedirs(os.path.join(d, "kdb.elab++"))
    if rebuild is not None or raw is not None:
        with open(os.path.join(d, "vcs_rebuild"), "w") as f:
            f.write(raw if raw is not None else "#!/bin/sh -e\n# This file is automatically generated by VCS.\n" + rebuild + "\n")
    for name, text in (files or {}).items():
        os.makedirs(os.path.dirname(os.path.join(sim, name)), exist_ok=True)
        with open(os.path.join(sim, name), "w") as f:
            f.write(text)
    for name, mtime in (elab or {}).items():
        path = os.path.join(d, "kdb.elab++", name)
        open(path, "w").close()
        os.utime(path, (mtime, mtime))
    return d


with tempfile.TemporaryDirectory() as tmp:
    def case(name, **kw):
        root = os.path.join(tmp, name)
        os.makedirs(root)
        return daidir(root, **kw)

    check("no override: an empty list",
          npi.overrides(case("none", rebuild="vcs '-full64' '-sverilog' '+define+ALT' '-top' 'tb' 'fifo.sv'")), [])
    check("-pvalue: listed",
          npi.overrides(case("pvalue", rebuild="vcs '-sverilog' '-pvalue+tb.u_fifo.DEPTH=32' 'fifo.sv'")), ["-pvalue+tb.u_fifo.DEPTH=32"])
    check("-parameters <file>: listed with its file",
          npi.overrides(case("params", rebuild="vcs '-sverilog' '-parameters' 'p.txt' 'fifo.sv'")), ["-parameters p.txt"])
    check("an override in a -f file (next to the daidir): listed",
          npi.overrides(case("ffile", rebuild="vcs '-sverilog' '-f' 'files.f'",
                             files={"files.f": "fifo.sv\n// a comment\n-pvalue+tb.W=4\n"})), ["-pvalue+tb.W=4"])
    check("a -f file that can't be read: unknown (None)",
          npi.overrides(case("lost", rebuild="vcs '-sverilog' '-f' 'gone.f'")), None)
    check("no vcs_rebuild: unknown (None)", npi.overrides(case("norebuild")), None)
    # Real vcs_rebuild files (fixture/vcs_rebuild). The -f file is ../opts.f from where VCS ran.
    check("real, no override: an empty list", npi.overrides(case("real-none", raw=real("none"))), [])
    check("real, -pvalue in a -f file: listed",
          npi.overrides(case("real-ffile", raw=real("ffile"), files={"../opts.f": "-pvalue+tb.u_fifo.DEPTH=32\n"})),
          ["-pvalue+tb.u_fifo.DEPTH=32"])
    check("real, -pvalue from a shell variable (recorded expanded): listed",
          npi.overrides(case("real-cmdline", raw=real("cmdline"))), ["-pvalue+tb.u_fifo.DEPTH=8"])
    check("real, +pvalue+ (VCS takes it): listed", npi.overrides(case("real-plus", raw=real("plus"))), ["+pvalue+tb.u_fifo.DEPTH=4"])
    # Fail closed: anything the scan can't be sure it read in full is unknown (None), never [].
    check("an unexpanded variable on the command line: unknown",
          npi.overrides(case("var", rebuild="vcs '-sverilog' $VCS_OPTS 'fifo.sv'")), None)
    check("a variable in a -f file: unknown",
          npi.overrides(case("fvar", rebuild="vcs '-sverilog' '-f' 'files.f'", files={"files.f": "fifo.sv\n${PROJ}/opts\n"})), None)
    check("a command substitution: unknown",
          npi.overrides(case("subst", rebuild="vcs '-sverilog' `cat opts` 'fifo.sv'")), None)
    check("no vcs command (a wrapper that runs make): unknown",
          npi.overrides(case("make", rebuild="exec make -C .. sim")), None)
    check("an override spelling the scan doesn't list (any token naming pvalue or parameters): listed",
          npi.overrides(case("spell", rebuild="vcs '-sverilog' '-pvalues=tb.W=4' 'fifo.sv'")), ["-pvalues=tb.W=4"])
    check("the vcs command after cd and env lines: its arguments",
          npi.overrides(case("cdenv", rebuild="cd /work/sim\nexport LM_LICENSE_FILE=1\nvcs '-sverilog' '-pvalue+tb.W=2' 'fifo.sv'")), ["-pvalue+tb.W=2"])
    # F1b: with -o out/simv the daidir is out/simv.daidir, and a relative -f path is VCS's working
    # directory's (the folder above out/), never the daidir's folder (a file of that name there).
    check("real, -o out/simv: the -f file where VCS ran, not the one next to the daidir",
          npi.overrides(case("real-outdir", raw=real("outdir"), sub="out",
                             files={"opts.f": "-pvalue+tb.u_fifo.DEPTH=32\n", "out/opts.f": "fifo.sv\n"})),
          ["-pvalue+tb.u_fifo.DEPTH=32"])
    check("-o with an absolute folder and a relative -f path: unknown (where VCS ran is not known)",
          npi.overrides(case("absout", rebuild="vcs '-f' 'opts.f' 't.sv' '-o' '/elsewhere/simv'", files={"opts.f": "t.sv\n"})), None)
    check("-o out/simv but the daidir is not in an out/ folder: unknown",
          npi.overrides(case("moved", rebuild="vcs '-f' 'opts.f' 't.sv' '-o' 'out/simv'", files={"opts.f": "t.sv\n"})), None)
    # F1c: the vcs command is its line's command (after env and VAR= assignments); a wrapper with
    # options before a token named vcs is no vcs command.
    check("a wrapper whose arguments include a vcs path: unknown",
          npi.overrides(case("wrapper", rebuild="runvcs '-pvalue+X=1' '-y' '/tools/vcs' 't.sv'")), None)
    check("vcs by absolute path after env assignments: its arguments",
          npi.overrides(case("envabs", rebuild="env A=1 B=2 /tools/bin/vcs '-pvalue+tb.W=1' 't.sv'")), ["-pvalue+tb.W=1"])
    # F1d: words match option tokens only, not a file named for parameters.
    check("a source file named parameters_pkg.sv: no override",
          npi.overrides(case("pkgname", rebuild="vcs '-sverilog' 'rtl/parameters_pkg.sv' 't.sv'")), [])
    # F1e: an -o set inside a file list moves where VCS put the daidir, which the scan can't follow.
    check("-o inside an -f file: unknown",
          npi.overrides(case("fileout", rebuild="vcs '-f' 'opts.f' 't.sv'",
                             files={"opts.f": "-o out/simv\n-f more.f\n", "more.f": "t.sv\n"})), None)
    # F1e, the reviewer's decoy: ./opts.f sets -o out/simv (so the daidir is out/simv.daidir) and a
    # same-named out/opts.f without the override sits next to the daidir. Which one VCS read is not
    # known: unknown.
    check("a relative -f, no command-line -o, a same-named file above the daidir's folder: unknown",
          npi.overrides(case("decoy", rebuild="vcs '-f' 'opts.f' 't.sv'", sub="out",
                             files={"opts.f": "-o out/simv\n-pvalue+tb.W=1\n", "out/opts.f": "t.sv\n"})), None)
    # The same decoy through a top-level -F: the -F file's own name is found from where VCS ran,
    # like -f's (only the paths inside it are relative to the file), so the same walk applies.
    check("a relative -F, no command-line -o, a same-named file above the daidir's folder: unknown",
          npi.overrides(case("decoyF", rebuild="vcs '-F' 'opts.f' 't.sv'", sub="out",
                             files={"opts.f": "-o out/simv\n-override_timescale=1ns/1ps\n-pvalue+tb.W=1\n",
                                    "out/opts.f": "t.sv\n"})), None)
    check("-o=out/simv (another -o spelling): unknown",
          npi.overrides(case("oeq", rebuild="vcs '-f' 'opts.f' '-o=out/simv'", sub="out", files={"out/opts.f": "t.sv\n"})), None)
    # Only -o's own spellings: options that merely start with -o are read as usual.
    check("-override_timescale on the command line and in a -f file: no override",
          npi.overrides(case("otimescale", rebuild="vcs '-override_timescale=1ns/1ps' '-f' 'files.f'",
                             files={"files.f": "-override_timescale=1ns/1ps\nt.sv\n"})), [])
    check("-o./out/simv glued (no space): unknown",
          npi.overrides(case("oglued", rebuild="vcs '-f' 'files.f' '-o./out/simv'", files={"files.f": "t.sv\n"})), None)
    # F1f: only one vcs line can be the compile; with two the scan can't tell which made the KDB.
    check("two vcs lines: unknown",
          npi.overrides(case("twovcs", rebuild="vcs 't.sv'\nvcs '-pvalue+tb.W=1' 't.sv'")), None)
    # -o's directory part is normalised: ./simv and out/../simv put the daidir next to where VCS ran.
    check("-o ./simv: the -f file next to the daidir",
          npi.overrides(case("dotout", rebuild="vcs '-f' 'opts.f' '-o' './simv'", files={"opts.f": "-pvalue+tb.W=3\n"})), ["-pvalue+tb.W=3"])
    check("-o out/../simv: the -f file next to the daidir",
          npi.overrides(case("upout", rebuild="vcs '-f' 'opts.f' '-o' 'out/../simv'", files={"opts.f": "-pvalue+tb.W=5\n"})), ["-pvalue+tb.W=5"])
    check("a KDB with no files: no compile time (None, not 0)", npi.compiled_at(case("empty")), None)
    check("the newest file's time, in ms", npi.compiled_at(case("dated", elab={"a.db": 1000, "b.db": 2000})), 2000000)

print("TRACE KDB EXPORTER CHECKS PASSED" if failures == 0 else "TRACE KDB EXPORTER CHECKS FAILED: %d" % failures)
sys.exit(1 if failures else 0)
